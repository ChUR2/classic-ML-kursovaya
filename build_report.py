def cv_scores() -> dict[str, dict[str, float]]:
    """Прочитать результаты кросс-валидации из кэша."""
    scores: dict[str, dict[str, float]] = {}
    for path in sorted((RES / "cache").glob("*.json")):
        task, model = path.stem.split("__", 1)
        scores.setdefault(task, {})[model.replace("_", " ").strip()] = json.loads(
            path.read_text(encoding="utf-8")
        )["score"]
    return scores


def test_metrics(task: str) -> pd.DataFrame:
    """Прочитать метрики на отложенном тесте."""
    return pd.read_csv(RES / f"{task}_test_metrics.csv")


def top_features(task: str, n: int = 6) -> str:
    """Список наиболее важных признаков задачи."""
    path = RES / f"{task}_importance.csv"
    if not path.exists():
        return "—"
    frame = pd.read_csv(path)
    return ", ".join(frame["признак"].head(n))


def summary_rows(scores: dict) -> list[list[str]]:
    """Сводная таблица по всем семи задачам."""
    rows = [["Задача", "Лучшая модель<br/>(по CV)", "CV",
             "Лучшая модель<br/>(на тесте)", "Тест", "Baseline",
             "Лучшая линейная<br/>модель, CV"]]
    for task, title in TASK_TITLES.items():
        by_cv = sorted(scores[task].items(), key=lambda kv: -kv[1])
        frame = test_metrics(task)
        key = "R2" if task.endswith("_reg") else "ROC-AUC"
        linear = max(scores[task].get("Ridge", -9),
                     scores[task].get("Logistic Regression", -9))
        baseline = "0.000" if task.endswith("_reg") else "0.500"
        rows.append([
            title, by_cv[0][0], f"{by_cv[0][1]:.3f}",
            frame.iloc[0]["модель"], f"{frame.iloc[0][key]:.3f}",
            baseline, f"{linear:.3f}",
        ])
    return rows


def model_table(task: str, scores: dict) -> list[list[str]]:
    """Полная таблица моделей для одной задачи."""
    key = "R2" if task.endswith("_reg") else "ROC-AUC"
    extra = (["RMSE (log10)", "MAE (log10)", "медианная ошибка, раз"]
             if task.endswith("_reg") else ["PR-AUC", "Accuracy", "F1"])
    frame = test_metrics(task)
    header = ["Модель", "CV", "Тест R²" if key == "R2" else "Тест ROC-AUC"] + [
        e.replace("медианная ошибка, раз", "Ошибка, раз") for e in extra
    ]
    rows = [header]
    for _, row in frame.iterrows():
        name = row["модель"]
        cv = scores[task].get(name.replace("(", "").replace(")", "")
                              .replace("  ", " ").strip(), None)
        if cv is None:
            cv = next((v for k, v in scores[task].items()
                       if k.split()[0] == name.split()[0]), float("nan"))
        rows.append([name, f"{cv:.3f}", f"{row[key]:.3f}"] +
                    [f"{row[e]:.3f}" for e in extra])
    return rows


