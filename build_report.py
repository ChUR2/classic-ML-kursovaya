def para(text: str, style: str = "body"):
    """Абзац заданного стиля."""
    return Paragraph(text, S[style])


def bullets(items: list[str]):
    """Маркированный список."""
    return [Paragraph(f"• {item}", S["bullet"]) for item in items]


def figure(name: str, caption: str, width: float = 16.5):
    """Изображение с подписью, не разрываемое между страницами."""
    path = FIG / name
    if not path.exists():
        return Spacer(1, 1)
    from PIL import Image as PILImage

    with PILImage.open(path) as img:
        ratio = img.height / img.width
    w = width * cm
    return KeepTogether([
        Image(str(path), width=w, height=w * ratio),
        para(caption, "caption"),
    ])


def table(data: list[list[str]], widths: list[float], header: bool = True,
          font_size: float = 8.0, highlight_first_col: bool = False):
    """Таблица с единым оформлением."""
    rows = []
    for i, row in enumerate(data):
        style_name = "cellb" if (header and i == 0) else "cell"
        rows.append([
            Paragraph(str(c), S["cellb"] if (highlight_first_col and j == 0
                                             and i > 0) else S[style_name])
            for j, c in enumerate(row)
        ])
    tbl = Table(rows, colWidths=[w * cm for w in widths], repeatRows=1 if header else 0)
    style = [
        ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#B0B8C4")),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("TOPPADDING", (0, 0), (-1, -1), 3),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
        ("LEFTPADDING", (0, 0), (-1, -1), 4),
        ("RIGHTPADDING", (0, 0), (-1, -1), 4),
    ]
    if header:
        style += [
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#D9E2F3")),
            ("ROWBACKGROUNDS", (0, 1), (-1, -1),
             [colors.white, colors.HexColor("#F2F5FA")]),
        ]
    tbl.setStyle(TableStyle(style))
    return tbl


